import { readFile, writeFile } from 'node:fs/promises'
import postcss from 'postcss'
import { JSDOM } from 'jsdom'
import sharp from 'sharp'

// Compatibility adapter: author appearance only in globals.css. Ship resolved,
// inline CSS and a PNG rendition of the existing mark to email clients.
const directory = 'supabase/functions/send-invitation'
const css = postcss.parse(await readFile('src/styles/globals.css', 'utf8'))
const tokens = new Map()
css.walkRules(':root', rule => rule.walkDecls(/^--/, declaration => tokens.set(declaration.prop, declaration.value)))

function resolve(value, trail = []) {
  return value.replace(/var\((--[\w-]+)\)/g, (_, name) => {
    if (!tokens.has(name) || trail.includes(name)) throw new Error(`Invalid email token: ${name}`)
    return resolve(tokens.get(name), [...trail, name])
  }).replace(/\b(\d*\.?\d+)rem\b/g, (_, rem) => `${Number(rem) * 16}px`)
}

const source = await readFile(`${directory}/templates/invitation-v2.html`, 'utf8')
if (/<style\b|\sstyle=|\s(?:bgcolor|color|width|height)=/i.test(source)) throw new Error('Email appearance belongs to globals.css.')
const document = new JSDOM(source).window.document
const knownClasses = new Set()
css.walkRules(rule => {
  if (!rule.selector.startsWith('.email-')) return
  if (rule.parent.type !== 'root' || !/^\.email-[\w-]+(?:,\s*\.email-[\w-]+)*$/.test(rule.selector)) {
    throw new Error(`Email rules must be simple, root-level classes: ${rule.selector}`)
  }
  rule.selector.split(/,\s*/).forEach(selector => knownClasses.add(selector.slice(1)))
  const declarations = []
  rule.walkDecls(declaration => declarations.push(`${declaration.prop}:${resolve(declaration.value)}${declaration.important ? '!important' : ''};`))
  for (const element of document.querySelectorAll(rule.selector)) {
    element.setAttribute('style', (element.getAttribute('style') || '') + declarations.join(''))
  }
})
for (const element of document.querySelectorAll('[class]')) {
  for (const className of element.classList) if (!knownClasses.has(className)) throw new Error(`Missing email style: ${className}`)
  // Outlook table/image fallbacks derive their dimensions and alignment from CSS.
  if (element.tagName === 'TABLE' && element.style.margin === '0px auto') element.setAttribute('align', 'center')
  if (element.tagName === 'IMG') {
    for (const dimension of ['width', 'height']) element.setAttribute(dimension, element.style[dimension].replace('px', ''))
  }
  element.removeAttribute('class')
}
const html = '<!DOCTYPE html>\n' + document.documentElement.outerHTML
if (/var\(|\b\d*\.?\d+rem\b/.test(html)) throw new Error('Email CSS must use resolved values.')
const svg = await readFile('public/orbit.svg', 'utf8')
const logo = await sharp(Buffer.from(svg)).resize(96, 96).png().toBuffer()
const generated = '// Generated by npm run emails:build. Author styles in src/styles/globals.css.\n'
  + `export const invitationHtmlV2 = ${JSON.stringify(html)}\n`
  + `export const invitationLogoV2 = ${JSON.stringify(logo.toString('base64'))}\n`
const output = `${directory}/invitation-v2.generated.ts`
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== generated) throw new Error('Email artifact is stale. Run npm run emails:build.')
  console.log('Email styles and generated artifact: valid.')
} else {
  await writeFile(output, generated)
  console.log(`Generated ${output}`)
}
